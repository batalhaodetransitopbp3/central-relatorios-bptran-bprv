'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.resolve(__dirname,'../apps_script_v10.gs'),'utf8');
const start=source.indexOf('function rcoConsolidateMergePodRow_(');
const end=source.indexOf('function rcoConsolidateMergeOpRow_(',start);
assert(start>0&&end>start);
const context={uid_:()=> 'unused',dateText_:x=>String(x||''),nowIso_:()=> 'NOW'};
vm.createContext(context);
vm.runInContext(source.slice(start,end),context);
const prior={REGISTRO_ID:'POD-1',HOUVE_ALTERACAO:'SIM',MOTIVO_ALTERACAO:'Excecao',GUARNICOES_PARTICIPANTES:'BST 01, TOR 01'};
const apply=x=>context.rcoConsolidateMergePodRow_(prior,{registroId:'POD-1',...x},'rco-1','BPRv','1 CPRv','2026-10-16');
assert.equal(apply({statusCumprimento:'Executado parcialmente'}).HOUVE_ALTERACAO,'SIM','missing flag must preserve P3 status');
assert.equal(apply({houveAlteracao:''}).HOUVE_ALTERACAO,'SIM','empty field must preserve P3 status');
assert.equal(apply({houveAlteracao:false}).HOUVE_ALTERACAO,'NÃO','explicit false is a deliberate update');
assert.equal(apply({houveAlteracao:true}).HOUVE_ALTERACAO,'SIM');
assert.equal(apply({HOUVE_ALTERACAO:'NÃO'}).HOUVE_ALTERACAO,'NÃO');
assert.equal(apply({}).GUARNICOES_PARTICIPANTES,'BST 01, TOR 01');
console.log('PASS missing POD change flag preserved, explicit changes honored');
